#!/usr/bin/env node
// Proves every semantic pairing in tokens.json → contrast-pairs against WCAG 2.2, in light and dark.
//   node skills/atlas/scripts/check_contrast.mjs [--md path]   (exit 1 if any pair is below its minimum)
// Text pairs use 1.4.3 (4.5:1) or 1.4.6 (7:1) as listed; non-text pairs use 1.4.11 (3:1).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { contrast } from "./palette.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(join(root, "assets/tokens/tokens.json"), "utf8"));
const hexToRgb = (h) => h.slice(1).match(/../g).map((x) => parseInt(x, 16));
function resolve(v) {
  if (typeof v !== "string") throw new Error(`bad token ${v}`);
  if (v.startsWith("{")) { const [fam, step] = v.slice(1, -1).split("."); const out = step ? t.primitive[fam]?.[step] : t.primitive[fam]; if (!out) throw new Error(`Unresolved ${v}`); return out; }
  return v;
}
const color = (theme, name) => { const v = t.semantic[theme][name]; if (!v) throw new Error(`Unknown semantic token ${name}`); return resolve(v); };

const rows = []; let failures = 0;
for (const theme of ["light", "dark"]) {
  for (const kind of ["text", "non-text"]) {
    for (const [fg, bgs, min] of t["contrast-pairs"][kind]) {
      for (const bg of bgs) {
        const f = color(theme, fg), b = color(theme, bg);
        const r = contrast(hexToRgb(f), hexToRgb(b));
        const ok = r >= min;
        if (!ok) failures++;
        rows.push({ theme, kind, fg, bg, f, b, r, min, ok });
      }
    }
  }
}
const fmt = (n) => n.toFixed(2);
const lines = ["# Atlas contrast report", "", "Generated by `scripts/check_contrast.mjs` from `tokens.json`. Every row is a pairing the components actually use.", "`min` is the WCAG 2.2 criterion applied: 4.5 = 1.4.3 text (AA), 7 = 1.4.6 text (AAA), 3 = 1.4.11 non-text (AA), 1.5 / 1 = decorative or exempt (reported only).", ""];
for (const theme of ["light", "dark"]) {
  lines.push(`## ${theme[0].toUpperCase() + theme.slice(1)} theme`, "", "| Kind | Foreground | Background | Ratio | Min | Result |", "|---|---|---|---|---|---|");
  for (const r of rows.filter((x) => x.theme === theme)) lines.push(`| ${r.kind} | \`${r.fg}\` ${r.f} | \`${r.bg}\` ${r.b} | ${fmt(r.r)}:1 | ${r.min} | ${r.ok ? "pass" : "**FAIL**"} |`);
  lines.push("");
}
const md = lines.join("\n");
const i = process.argv.indexOf("--md");
if (i > 0) { writeFileSync(process.argv[i + 1], md); console.log(`wrote ${process.argv[i + 1]}`); }
for (const r of rows) if (!r.ok || process.argv.includes("--all")) console.log(`${r.ok ? "ok  " : "FAIL"} ${r.theme.padEnd(5)} ${r.kind.padEnd(8)} ${r.fg} on ${r.bg}: ${fmt(r.r)} (min ${r.min})`);
console.log(`${rows.length - failures}/${rows.length} pairs pass`);
process.exit(failures ? 1 : 0);
