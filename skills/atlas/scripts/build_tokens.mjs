#!/usr/bin/env node
// Builds platform outputs from assets/tokens/tokens.json (the single source of truth).
//   node skills/atlas/scripts/build_tokens.mjs
// Outputs:
//   assets/tokens/atlas-tokens.css   CSS custom properties (--at-*): primitives, light semantic on :root,
//                                    dark semantic under [data-theme="dark"] and under prefers-color-scheme
//                                    when data-theme is unset, plus type / space / radius / size / shadow / z / motion.
//   assets/tokens/tailwind.preset.js Tailwind preset wired to the same variables.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(join(root, "assets/tokens/tokens.json"), "utf8"));
const header = (c) => `${c} GENERATED by scripts/build_tokens.mjs from tokens.json — do not edit by hand.`;
const entries = (o) => Object.entries(o).filter(([k]) => !k.startsWith("_"));
const px = (n) => `${n}px`;
const cssRef = (v) => (typeof v === "string" && v.startsWith("{") ? `var(--at-${v.slice(1, -1).replace(".", "-")})` : v);

// ---------- CSS ----------
{
  const L = [header("/*") + " */", "", "/* Atlas tokens. Light is the default; dark follows the OS unless data-theme is set on <html>. */", ""];
  const block = (sel, lines) => [`${sel} {`, ...lines, "}", ""];
  const semantic = (o) => entries(o).map(([k, v]) => `  --at-${k}: ${cssRef(v)};`);

  const base = [];
  for (const [fam, steps] of entries(t.primitive)) {
    if (typeof steps === "string") base.push(`  --at-${fam}: ${steps};`);
    else for (const [step, hex] of entries(steps)) base.push(`  --at-${fam}-${step}: ${hex};`);
  }
  base.push("", "  color-scheme: light;", ...semantic(t.semantic.light), "");
  for (const [k, v] of entries(t.type.family)) base.push(`  --at-font-${k}: ${v};`);
  for (const [k, s] of entries(t.type.scale)) {
    base.push(`  --at-text-${k}-size: ${s.size}rem;`, `  --at-text-${k}-line: ${s.line};`, `  --at-text-${k}-weight: ${s.weight};`, `  --at-text-${k}-tracking: ${s.tracking}em;`);
  }
  base.push("");
  for (const [k, v] of entries(t.space)) base.push(`  --at-space-${k}: ${px(v)};`);
  for (const [k, v] of entries(t.radius)) base.push(`  --at-radius-${k}: ${px(v)};`);
  for (const [k, v] of entries(t.size)) base.push(`  --at-size-${k}: ${px(v)};`);
  for (const [k, v] of entries(t.shadow)) base.push(`  --at-shadow-${k}: ${v};`);
  for (const [k, v] of entries(t.z)) base.push(`  --at-z-${k}: ${v};`);
  for (const [k, v] of entries(t.motion.duration)) base.push(`  --at-duration-${k}: ${v}ms;`);
  for (const [k, v] of entries(t.motion.easing)) base.push(`  --at-ease-${k}: ${v};`);
  for (const [k, v] of entries(t.container)) base.push(`  --at-container-${k}: ${px(v)};`);
  L.push(...block(":root", base));

  const dark = ["  color-scheme: dark;", ...semantic(t.semantic.dark)];
  L.push("@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', ...dark.map((l) => "  " + l), "  }", "}", "");
  L.push(...block(':root[data-theme="dark"]', dark));
  L.push("/* Reduced motion: collapse every duration (WCAG 2.3.3). */");
  L.push(...block("@media (prefers-reduced-motion: reduce) {\n  :root", entries(t.motion.duration).map(([k]) => `    --at-duration-${k}: 0ms;`).concat(["  }"])));
  writeFileSync(join(root, "assets/tokens/atlas-tokens.css"), L.join("\n").replace(/\n  }\n}\n\n$/, "\n  }\n}\n"));
}

// ---------- Tailwind ----------
{
  const colors = {};
  for (const [fam, steps] of entries(t.primitive)) {
    if (typeof steps === "string") colors[fam] = `var(--at-${fam})`;
    else { colors[fam] = {}; for (const step of Object.keys(steps)) colors[fam][step] = `var(--at-${fam}-${step})`; }
  }
  for (const k of Object.keys(t.semantic.light)) {
    if (k.startsWith("_")) continue;
    if (typeof colors[k] === "object") colors[k].DEFAULT = `var(--at-${k})`; // brand → brand.DEFAULT keeps the scale
    else colors[k] = `var(--at-${k})`;
  }
  const fontSize = {};
  for (const [k, s] of entries(t.type.scale)) fontSize[k] = [`var(--at-text-${k}-size)`, { lineHeight: `var(--at-text-${k}-line)`, fontWeight: `var(--at-text-${k}-weight)`, letterSpacing: `var(--at-text-${k}-tracking)` }];
  const spacing = Object.fromEntries(entries(t.space).map(([k]) => [k.replace("_", "."), `var(--at-space-${k})`]));
  const preset = {
    theme: {
      extend: {
        colors,
        fontFamily: { sans: ["var(--at-font-sans)"], mono: ["var(--at-font-mono)"] },
        fontSize,
        spacing,
        borderRadius: Object.fromEntries(entries(t.radius).map(([k]) => [k === "md" ? "DEFAULT" : k, `var(--at-radius-${k})`])),
        boxShadow: Object.fromEntries(entries(t.shadow).map(([k]) => [k, `var(--at-shadow-${k})`])),
        zIndex: Object.fromEntries(entries(t.z).map(([k]) => [k, `var(--at-z-${k})`])),
        transitionDuration: Object.fromEntries(entries(t.motion.duration).map(([k]) => [k, `var(--at-duration-${k})`])),
        transitionTimingFunction: Object.fromEntries(entries(t.motion.easing).map(([k]) => [k, `var(--at-ease-${k})`])),
        screens: Object.fromEntries(entries(t.breakpoint).map(([k, v]) => [k, px(v)])),
        outlineWidth: { focus: "var(--at-size-focus-width)" },
        outlineOffset: { focus: "var(--at-size-focus-offset)" },
        minHeight: { control: "var(--at-size-control-md)", target: "var(--at-size-target-min)", touch: "var(--at-size-target-touch)" },
        minWidth: { target: "var(--at-size-target-min)", touch: "var(--at-size-target-touch)" },
      },
    },
  };
  writeFileSync(join(root, "assets/tokens/tailwind.preset.js"), `${header("//")}\n// Import atlas-tokens.css first; this preset only maps utilities to the variables.\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`);
}
console.log("built atlas-tokens.css and tailwind.preset.js");
